def analysis_to_markdown(record: MeetingRecord) -> str:
    """Render a MeetingRecord as a polished Markdown report."""
    a: MeetingAnalysis = record.analysis
    lines: list[str] = []

    lines.append(f"# {record.title}")
    lines.append("")
    lines.append(f"*Generated by MeetingMind AI on {record.created_at.strftime('%Y-%m-%d %H:%M UTC')}*")
    lines.append("")
    lines.append(f"**Category:** {a.category.value}  ")
    lines.append(f"**Sentiment:** {a.sentiment.value}")
    lines.append("")

    lines.append("## Executive Summary")
    lines.append(a.executive_summary)
    lines.append("")

    lines.append("## Detailed Summary")
    lines.append(a.detailed_summary)
    lines.append("")

    lines.append("## Key Decisions")
    if a.key_decisions:
        lines.extend(f"- {d}" for d in a.key_decisions)
    else:
        lines.append("_No key decisions recorded._")
    lines.append("")

    lines.append("## Action Items")
    if a.action_items:
        lines.append("| Task | Owner | Due Date | Priority |")
        lines.append("|---|---|---|---|")
        for item in a.action_items:
            lines.append(
                f"| {item.task} | {item.owner} | {format_due_date(item.due_date)} | {item.priority.value} |"
            )
    else:
        lines.append("_No action items identified._")
    lines.append("")

    lines.append("## Risks")
    lines.extend(f"- {r}" for r in a.risks) if a.risks else lines.append("_None identified._")
    lines.append("")

    lines.append("## Blockers")
    lines.extend(f"- {b}" for b in a.blockers) if a.blockers else lines.append("_None identified._")
    lines.append("")

    lines.append("## Open Questions")
    lines.extend(f"- {q}" for q in a.open_questions) if a.open_questions else lines.append("_None identified._")
    lines.append("")

    lines.append("## Keywords")
    lines.append(", ".join(a.keywords) if a.keywords else "_None_")
    lines.append("")

    if a.suggested_next_meeting:
        lines.append("## Suggested Next Meeting")
        lines.append(a.suggested_next_meeting)
        lines.append("")

    lines.append("## Follow-up Email Draft")
    lines.append("```")
    lines.append(a.follow_up_email_draft or "(none)")
    lines.append("```")
    lines.append("")

    lines.append("## Full Transcript")
    lines.append("<details><summary>Click to expand</summary>")
    lines.append("")
    lines.append(record.transcript)
    lines.append("")
    lines.append("</details>")

    return "\n".join(lines)


def analysis_to_json(record: MeetingRecord) -> str:
    """Render a MeetingRecord as a pretty-printed JSON string."""
    return json.dumps(record.to_supabase_row(), indent=2, default=str)


def analysis_to_txt(record: MeetingRecord) -> str:
    """Render a MeetingRecord as a plain-text report (no markdown)."""
    a = record.analysis
    parts = [
        record.title,
        "=" * len(record.title),
        f"Generated: {record.created_at.strftime('%Y-%m-%d %H:%M UTC')}",
        f"Category: {a.category.value} | Sentiment: {a.sentiment.value}",
        "",
        "EXECUTIVE SUMMARY",
        "-" * 17,
        a.executive_summary,
        "",
        "DETAILED SUMMARY",
        "-" * 16,
        a.detailed_summary,
        "",
        "KEY DECISIONS",
        "-" * 13,
    ]
    parts += [f"- {d}" for d in a.key_decisions] or ["(none)"]
    parts += ["", "ACTION ITEMS", "-" * 12]
    if a.action_items:
        for item in a.action_items:
            parts.append(
                f"- [{item.priority.value}] {item.task} "
                f"(Owner: {item.owner}, Due: {format_due_date(item.due_date)})"
            )
    else:
        parts.append("(none)")
    parts += ["", "RISKS", "-" * 5]
    parts += [f"- {r}" for r in a.risks] or ["(none)"]
    parts += ["", "BLOCKERS", "-" * 8]
    parts += [f"- {b}" for b in a.blockers] or ["(none)"]
    parts += ["", "OPEN QUESTIONS", "-" * 14]
    parts += [f"- {q}" for q in a.open_questions] or ["(none)"]
    parts += ["", "FOLLOW-UP EMAIL DRAFT", "-" * 21, a.follow_up_email_draft or "(none)"]
    parts += ["", "FULL TRANSCRIPT", "-" * 15, record.transcript]
    return "\n".join(parts)


def save_export(content: str, out_dir: Path, filename: str) -> Path:
    """Write export content to disk and return the resulting path."""
    out_dir.mkdir(parents=True, exist_ok=True)
    path = out_dir / filename
    path.write_text(content, encoding="utf-8")
    return path
