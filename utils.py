"""
utils.py
========
Small, stateless helper functions shared across the app: date parsing,
export formatting (Markdown/JSON/TXT), and file utilities. Kept
dependency-light and side-effect-free (aside from explicit file writes)
so they're easy to unit test.
"""

from __future__ import annotations

import json
from datetime import date, datetime
from pathlib import Path
from typing import Union

from models import MeetingAnalysis, MeetingRecord

_MAX_UPLOAD_BYTES = 500 * 1024 * 1024  # 500 MB


def format_file_size(num_bytes: int) -> str:
    """Human-readable file size, e.g. 1536000 -> '1.5 MB'."""
    size = float(num_bytes)
    for unit in ("B", "KB", "MB", "GB"):
        if size < 1024 or unit == "GB":
            return f"{size:.1f} {unit}" if unit != "B" else f"{int(size)} {unit}"
        size /= 1024
    return f"{size:.1f} GB"


def is_upload_size_valid(num_bytes: int, max_bytes: int = _MAX_UPLOAD_BYTES) -> bool:
    return 0 < num_bytes <= max_bytes


def safe_filename(name: str) -> str:
    """Strip characters that are unsafe for filesystem paths."""
    keep = "-_.() "
    cleaned = "".join(c for c in name if c.isalnum() or c in keep).strip()
    return cleaned or "meeting"


def format_due_date(value: Union[date, None]) -> str:
    if value is None:
        return "Not specified"
    return value.strftime("%Y-%m-%d")


